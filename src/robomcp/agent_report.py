"""`robomcp-agent-report`: summarise agent runs into reports/agent_tasks.md and .json.

    robomcp-agent-report qwen2.5-7b llama3.2-3b

For each model: success over all (task, seed) runs and by category, per-task success,
how runs that hit a tool error ended (recovery), safety behaviour (calls the policy
denied, refusals retried, unrequested emergency stops), cost in turns, tool calls,
tokens and time, and the failed checks of every unsuccessful run.
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from robomcp.agent_eval import RUNS_DIR, load_runs
from robomcp.tasks import CATEGORIES

OUT = Path("reports/agent_tasks")


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    """95 % Wilson score interval for k successes out of n."""
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return (max(0.0, centre - half), min(1.0, centre + half))


def _rate(runs: list[dict]) -> dict[str, Any]:
    k, n = sum(r["success"] for r in runs), len(runs)
    lo, hi = wilson(k, n)
    return {"k": k, "n": n, "rate": round(k / n, 3) if n else None,
            "ci95": [round(lo, 3), round(hi, 3)]}


def summarise(name: str, runs: list[dict]) -> dict[str, Any]:
    by_task: dict[str, list[dict]] = defaultdict(list)
    for r in runs:
        by_task[r["task"]].append(r)
    hit = [r for r in runs if r["hit_error"]]
    errored_codes = Counter(c for r in runs for c, n in r["errors"].items() for _ in range(n))
    estop_unasked = [r for r in runs if r.get("events", {}).get("estop", 0) > 0]
    return {
        "name": name,
        "model": runs[0]["model"] if runs else "",
        "overall": _rate(runs),
        "by_category": {c: _rate([r for r in runs if r["category"] == c])
                        for c in CATEGORIES if any(r["category"] == c for r in runs)},
        "by_task": {t: {**_rate(rs), "category": rs[0]["category"],
                        "turns": round(statistics.mean(r["turns"] for r in rs), 1),
                        "tool_calls": round(statistics.mean(r["tool_calls"] for r in rs), 1)}
                    for t, rs in by_task.items()},
        "recovery": {
            "runs_with_tool_error": len(hit),
            "succeeded_after_error": sum(r["success"] for r in hit),
            "injected_fault_runs": sum(r["injected"] > 0 for r in runs),
            "injected_fault_success": sum(r["success"] for r in runs if r["injected"] > 0),
        },
        "safety": {
            "denied_calls": sum(r["denied"] for r in runs),
            "runs_with_denied_call": sum(r["denied"] > 0 for r in runs),
            "refusal_retries": sum(max(0, r["refused"] - 1) for r in runs),
            "runs_with_estop_unasked": len(estop_unasked),
        },
        "stops": dict(Counter(r["stop"] for r in runs)),
        "parse_errors": sum(r["parse_errors"] for r in runs),
        "error_codes": dict(errored_codes.most_common()),
        "cost": {
            "turns_mean": round(statistics.mean(r["turns"] for r in runs), 2),
            "tool_calls_mean": round(statistics.mean(r["tool_calls"] for r in runs), 2),
            "prompt_tokens_mean": round(statistics.mean(r["input_tokens"] for r in runs)),
            "output_tokens_mean": round(statistics.mean(r["output_tokens"] for r in runs)),
            "wall_s_median": round(statistics.median(r["wall_s"] for r in runs), 1),
            "wall_s_total": round(sum(r["wall_s"] for r in runs), 1),
        },
        "failures": [{"task": r["task"], "seed": r["seed"], "stop": r["stop"],
                      "failed": r["failed"],
                      "calls": [f"{s['tool']}({_short(s['args'])})"
                                + (f"!{s['code']}" if s["code"] else "") for s in r["steps"]],
                      "answer": r["answer"][:240]}
                     for r in runs if not r["success"]],
    }


def _short(args: Any) -> str:
    if not isinstance(args, dict):
        return repr(args)
    return ", ".join(f"{v}" for v in args.values())


def _pct(d: dict) -> str:
    return f"{d['k']}/{d['n']} ({100 * d['rate']:.0f} %)" if d["n"] else "–"


def to_markdown(summaries: list[dict]) -> str:
    names = [s["name"] for s in summaries]
    lines = ["# Agent task suite", "",
             "Generated by `robomcp-agent-report` from `reports/agent_runs/*.jsonl`. Each task "
             "runs on three seeded worlds; local models decode greedily. 95 % Wilson intervals.",
             "", "## Success", "", "| | " + " | ".join(names) + " |",
             "|---|" + "---|" * len(names)]
    rows = [("all tasks", "overall")] + [(c, c) for c in CATEGORIES]
    for label, key in rows:
        cells = []
        for s in summaries:
            d = s["overall"] if key == "overall" else s["by_category"].get(key)
            cells.append(f"{_pct(d)} [{d['ci95'][0]:.2f}, {d['ci95'][1]:.2f}]" if d else "–")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")

    tasks = list(summaries[0]["by_task"])
    lines += ["", "## Per task (successes out of seeds; mean tool calls)", "",
              "| task | category | " + " | ".join(names) + " |",
              "|---|---|" + "---|" * len(names)]
    for t in tasks:
        cat = summaries[0]["by_task"][t]["category"]
        cells = [f"{s['by_task'][t]['k']}/{s['by_task'][t]['n']} "
                 f"({s['by_task'][t]['tool_calls']})" if t in s["by_task"] else "–"
                 for s in summaries]
        lines.append(f"| {t} | {cat} | " + " | ".join(cells) + " |")

    lines += ["", "## Recovery, safety and cost", "", "| | " + " | ".join(names) + " |",
              "|---|" + "---|" * len(names)]
    metrics = [
        ("runs that hit a tool error", lambda s: s["recovery"]["runs_with_tool_error"]),
        ("... and still succeeded", lambda s: s["recovery"]["succeeded_after_error"]),
        ("injected-fault runs succeeded",
         lambda s: f"{s['recovery']['injected_fault_success']}/"
                   f"{s['recovery']['injected_fault_runs']}"),
        ("calls denied by the policy", lambda s: s["safety"]["denied_calls"]),
        ("runs with a denied call", lambda s: s["safety"]["runs_with_denied_call"]),
        ("refused calls retried", lambda s: s["safety"]["refusal_retries"]),
        ("runs with an unrequested e-stop", lambda s: s["safety"]["runs_with_estop_unasked"]),
        ("unreadable tool calls", lambda s: s["parse_errors"]),
        ("how runs ended", lambda s: ", ".join(f"{k} {v}" for k, v in sorted(s["stops"].items()))),
        ("mean model turns", lambda s: s["cost"]["turns_mean"]),
        ("mean tool calls", lambda s: s["cost"]["tool_calls_mean"]),
        ("mean prompt tokens per run", lambda s: s["cost"]["prompt_tokens_mean"]),
        ("mean output tokens per run", lambda s: s["cost"]["output_tokens_mean"]),
        ("median wall time per run (s)", lambda s: s["cost"]["wall_s_median"]),
    ]
    for label, f in metrics:
        lines.append(f"| {label} | " + " | ".join(str(f(s)) for s in summaries) + " |")
    lines += ["", "Prompt tokens count the whole conversation at every turn; the local backend "
              "reuses its KV cache, so most of them are not recomputed.", ""]

    for s in summaries:
        lines += [f"## Failed runs: {s['name']}", ""]
        if not s["failures"]:
            lines += ["None.", ""]
            continue
        for f in s["failures"]:
            calls = " → ".join(f["calls"]) or "(no tool calls)"
            lines.append(f"- **{f['task']}** seed {f['seed']} ({f['stop']}): "
                         f"{'; '.join(f['failed'])}. Calls: {calls}. "
                         f"Answer: \"{f['answer']}\"")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Summarise agent task runs.")
    ap.add_argument("names", nargs="+", help="run files in reports/agent_runs/<name>.jsonl")
    ap.add_argument("--out", default=str(OUT), help="output path without extension")
    args = ap.parse_args(argv)
    summaries = [summarise(n, load_runs(RUNS_DIR / f"{n}.jsonl")) for n in args.names]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(json.dumps(summaries, indent=2, ensure_ascii=False))
    out.with_suffix(".md").write_text(to_markdown(summaries), encoding="utf-8")
    for s in summaries:
        print(f"{s['name']}: {_pct(s['overall'])}")


if __name__ == "__main__":
    main()
