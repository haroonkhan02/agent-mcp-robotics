"""`robomcp-injection-report`: attack and utility numbers for the injection runs.

    robomcp-injection-report qwen2.5-7b-none qwen2.5-7b-spotlight qwen2.5-7b-scope \\
        --suite qwen2.5-7b-autonomous qwen2.5-7b-autonomous-scope

Reads reports/injection_runs/<name>.jsonl and writes reports/injection.md / .json. Per run
configuration it counts how often the planted instruction was tried (the model made the call
it asked for), how often it worked (the world or the answer ended up as the attacker wanted)
and how often the user's own request was still done. `--suite` adds the same configurations
on the 14-task benign suite (reports/agent_runs), which is what a defence costs in normal use.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from typing import Any

from robomcp.agent_eval import RUNS_DIR, load_runs
from robomcp.agent_report import wilson

INJ_DIR = Path("reports/injection_runs")
OUT = Path("reports/injection")


def _k(runs: list[dict], key: str) -> dict[str, Any]:
    k, n = sum(bool(r[key]) for r in runs), len(runs)
    lo, hi = wilson(k, n)
    return {"k": k, "n": n, "ci95": [round(lo, 2), round(hi, 2)]}


def summarise(name: str, runs: list[dict]) -> dict[str, Any]:
    by_task: dict[str, list[dict]] = defaultdict(list)
    for r in runs:
        by_task[r["task"]].append(r)
    return {
        "name": name, "model": runs[0]["model"], "prompt": runs[0].get("prompt", "default"),
        "defence": runs[0].get("defence", "none"), "scope": runs[0].get("scope", False),
        "attempted": _k(runs, "attack_attempted"), "succeeded": _k(runs, "attack_succeeded"),
        "task_done": _k(runs, "success"),
        "scope_denied_calls": sum(r.get("scope_denied", 0) for r in runs),
        "policy_denied_calls": sum(r["denied"] for r in runs),
        "by_task": {t: {key: sum(bool(r[key]) for r in rs) for key in
                        ("attack_attempted", "attack_succeeded", "success")} | {"n": len(rs)}
                    for t, rs in by_task.items()},
        "attacked_runs": [{"task": r["task"], "seed": r["seed"], "succeeded": r["attack_succeeded"],
                           "task_done": r["success"],
                           "calls": [f"{s['tool']}({', '.join(map(str, s['args'].values()))})"
                                     + (f"!{s['code']}" if s["code"] else "")
                                     for s in r["steps"] if isinstance(s["args"], dict)]}
                          for r in runs if r["attack_attempted"]],
    }


def _f(d: dict) -> str:
    return f"{d['k']}/{d['n']}"


def to_markdown(rows: list[dict], suites: list[dict]) -> str:
    names = [r["name"] for r in rows]
    out = ["# Prompt-injection results", "",
           "Generated by `robomcp-injection-report` from `reports/injection_runs/*.jsonl`. "
           "14 tasks x 5 seeds per configuration, greedy decoding. Attempted = the model made "
           "a call the planted text asked for (even if the server refused it). Succeeded = "
           "the attack's goal was reached. User task done = the actual request was completed.",
           "", "## Per configuration", "",
           "| configuration | model | spotlight | scope guard | attempted | succeeded | "
           "user task done | calls stopped by scope / policy |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['name']} | {r['model'].split('/')[-1]} | {r['defence'] == 'spotlight'}"
                   f" | {r['scope']} | {_f(r['attempted'])} | {_f(r['succeeded'])} "
                   f"[{r['succeeded']['ci95'][0]}, {r['succeeded']['ci95'][1]}] | "
                   f"{_f(r['task_done'])} | {r['scope_denied_calls']} / "
                   f"{r['policy_denied_calls']} |")
    tasks = list(rows[0]["by_task"])
    out += ["", "## Per task (attack succeeded / attempted / user task done, out of 5 seeds)",
            "", "| task | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for t in tasks:
        cells = []
        for r in rows:
            d = r["by_task"].get(t)
            cells.append(f"{d['attack_succeeded']} / {d['attack_attempted']} / {d['success']}"
                         if d else "–")
        out.append(f"| {t} | " + " | ".join(cells) + " |")
    if suites:
        out += ["", "## What the defences cost on the benign suite (14 tasks x 3 seeds)", "",
                "| configuration | successes |", "|---|---|"]
        for s in suites:
            out.append(f"| {s['name']} | {s['k']}/{s['n']} ({100 * s['k'] / s['n']:.0f} %) |")
        out += ["", "| task | " + " | ".join(s["name"] for s in suites) + " |",
                "|---|" + "---|" * len(suites)]
        for t in suites[0]["by_task"]:
            out.append(f"| {t} | " + " | ".join(
                f"{s['by_task'][t][0]}/{s['by_task'][t][1]}" for s in suites) + " |")
    out += ["", "## Runs where the model tried the planted instruction", ""]
    for r in rows:
        out += [f"### {r['name']}", ""]
        if not r["attacked_runs"]:
            out += ["None.", ""]
            continue
        for a in r["attacked_runs"]:
            out.append(f"- {a['task']} seed {a['seed']}: "
                       f"{'attack worked' if a['succeeded'] else 'attack failed'}, "
                       f"user task {'done' if a['task_done'] else 'not done'}. "
                       f"Calls: {' → '.join(a['calls']) or '(none)'}")
        out.append("")
    return "\n".join(out)


def suite_summary(name: str) -> dict[str, Any]:
    runs = load_runs(RUNS_DIR / f"{name}.jsonl")
    by_task: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    for r in runs:
        by_task[r["task"]][0] += int(r["success"])
        by_task[r["task"]][1] += 1
    return {"name": name, "k": sum(r["success"] for r in runs), "n": len(runs),
            "by_task": dict(by_task)}


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Summarise prompt-injection runs.")
    ap.add_argument("names", nargs="+", help="files in reports/injection_runs/<name>.jsonl")
    ap.add_argument("--suite", nargs="*", default=[],
                    help="benign-suite runs in reports/agent_runs/<name>.jsonl")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    rows = [summarise(n, load_runs(INJ_DIR / f"{n}.jsonl")) for n in args.names]
    suites = [suite_summary(n) for n in args.suite]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.with_suffix(".json").write_text(
        json.dumps({"injection": rows, "suite": suites}, indent=2, ensure_ascii=False))
    out.with_suffix(".md").write_text(to_markdown(rows, suites), encoding="utf-8")
    for r in rows:
        print(f"{r['name']}: attempted {_f(r['attempted'])}, succeeded {_f(r['succeeded'])}, "
              f"task done {_f(r['task_done'])}")


if __name__ == "__main__":
    main()
